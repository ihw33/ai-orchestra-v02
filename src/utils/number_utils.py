def is_even(n: int) -> bool:
    """숫자가 짝수인지 판별"""
    return n % 2 == 0

def is_prime(n: int) -> bool:
    """숫자가 소수인지 판별"""
    if n < 2:
        return False
    for i in range(2, int(n ** 0.5) + 1):
        if n % i == 0:
            return False
    return True

def factorial(n: int) -> int:
    """팩토리얼 계산"""
    if n < 0:
        raise ValueError("음수는 팩토리얼 계산 불가")
    if n == 0 or n == 1:
        return 1
    result = 1
    for i in range(2, n + 1):
        result *= i
    return result


