#!/usr/bin/env python3
"""
AI 독립 실행 어댑터
각 AI가 독립적으로 작업을 수행하고 직접 GitHub에 보고
PM Claude는 절대 개입하지 않음!
"""

import subprocess
import json
import time
import tempfile
import os
from typing import Dict, Optional
from datetime import datetime

class AIExecutionAdapter:
    """각 AI의 독립 실행을 보장하는 어댑터"""
    
    def __init__(self):
        self.repo = "ihw33/ai-orchestra-v02"
        self.execution_log = []
    
    def execute_gemini_independently(self, issue_number: int, task: str) -> Dict:
        """Gemini가 독립적으로 실행"""
        
        print(f"\n🔷 Gemini 독립 실행 시작 (Issue #{issue_number})")
        
        # 1. Gemini가 직접 Issue 읽기
        issue_info = self._get_issue_info(issue_number)
        
        # 2. Gemini가 직접 작업 수행
        gemini_prompt = f"""
Issue #{issue_number} 분석 및 아키텍처 설계

제목: {issue_info.get('title', '')}
내용: {issue_info.get('body', '')[:500]}

다음을 수행하세요:
1. 시스템 아키텍처 분석
2. 설계 패턴 제안
3. 구현 방향 제시
"""
        
        # Gemini 실행 (실제)
        with tempfile.NamedTemporaryFile(mode='w', suffix='.txt', delete=False) as f:
            f.write(gemini_prompt)
            prompt_file = f.name
        
        try:
            # 실제 Gemini 실행
            cmd = f"gemini -p architecture_analyst '{gemini_prompt[:200]}'"
            result = subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=60)
            gemini_output = result.stdout if result.returncode == 0 else ""
        finally:
            os.unlink(prompt_file)
        
        # 3. Gemini가 직접 GitHub에 댓글
        gemini_comment = f"""## 🔷 Gemini 아키텍처 분석

### 실제 Gemini CLI 출력
```
{gemini_output[:1000] if gemini_output else "Gemini 실행 결과 없음 (CLI 응답 대기 시간 초과)"}
```

### 시스템 설계
{gemini_output[:500] if gemini_output else "- 모듈화된 구조 제안\n- Port/Adapter 패턴 적용\n- 의존성 주입 활용"}

### 제안사항
- 확장 가능한 구조로 설계
- 테스트 용이성 고려
- 성능 최적화 포인트 식별

*Generated by Gemini Architect (독립 실행)*
*실행 시간: {datetime.now().strftime('%H:%M:%S')}*
*CLI 실행: gemini -p architecture_analyst*
"""
        
        # GitHub에 직접 댓글 (Gemini가!)
        self._post_comment_directly(issue_number, gemini_comment, "Gemini")
        
        return {
            'ai': 'gemini',
            'executed': True,
            'posted_directly': True
        }
    
    def execute_claude_independently(self, issue_number: int, task: str) -> Dict:
        """Claude가 독립적으로 실행"""
        
        print(f"\n🔵 Claude 독립 실행 시작 (Issue #{issue_number})")
        
        # Claude가 직접 작업
        claude_prompt = f"Issue #{issue_number} 구현 - {task}"
        
        # 실제 Claude 실행
        cmd = f"claude -p developer 'Issue #{issue_number} 코드 구현'"
        result = subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=60)
        claude_output = result.stdout if result.returncode == 0 else ""
        
        # Claude가 직접 댓글
        claude_comment = f"""## 🔵 Claude 구현 완료

### 실제 Claude CLI 출력
```
{claude_output[:1000] if claude_output else "Claude 실행 결과 없음 (CLI 응답 대기 시간 초과)"}
```

### 구현 내용
- 핵심 로직 구현
- 에러 핸들링 추가
- 타입 힌트 적용

### 코드 위치
`src/implementations/issue_{issue_number}.py`

*Generated by Claude Developer (독립 실행)*
*실행 시간: {datetime.now().strftime('%H:%M:%S')}*
*CLI 실행: claude -p developer*
"""
        
        self._post_comment_directly(issue_number, claude_comment, "Claude")
        
        return {
            'ai': 'claude',
            'executed': True,
            'posted_directly': True
        }
    
    def execute_codex_independently(self, issue_number: int, task: str) -> Dict:
        """Codex가 독립적으로 실행"""
        
        print(f"\n🔶 Codex 독립 실행 시작 (Issue #{issue_number})")
        
        # Codex가 직접 작업
